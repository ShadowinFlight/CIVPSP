#!/usr/bin/env python3
"""Generate src/gen/strings_gen.{h,c} from assets/strings.csv.

The CSV is the single source of truth for UI text.  Both the English and
Chinese columns are emitted; the runtime language toggle selects one and falls
back to English when a Chinese row is empty.
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "assets" / "strings.csv"
OUT_DIR = ROOT / "src" / "gen"


def c_escape(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
    )


def main() -> None:
    rows: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    with CSV_PATH.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if (
            not reader.fieldnames
            or "id" not in reader.fieldnames
            or "en" not in reader.fieldnames
        ):
            raise SystemExit("strings.csv must contain id,en columns")
        for row in reader:
            sid = (row.get("id") or "").strip()
            if not sid:
                continue
            if not re.fullmatch(r"[A-Z][A-Z0-9_]*", sid):
                raise SystemExit(f"invalid string id: {sid!r}")
            if sid in seen:
                raise SystemExit(f"duplicate string id: {sid}")
            seen.add(sid)
            en = (row.get("en") or "").strip()
            zh = (row.get("zh") or "").strip()
            if not en:
                raise SystemExit(f"empty English string: {sid}")
            rows.append((sid, en, zh))

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    h_path = OUT_DIR / "strings_gen.h"
    c_path = OUT_DIR / "strings_gen.c"

    h_lines = [
        "/* Generated by tools/gen_strings.py. Do not edit by hand. */",
        "#ifndef STRINGS_GEN_H",
        "#define STRINGS_GEN_H",
        "",
        "typedef enum {",
    ]
    for i, (sid, _, _) in enumerate(rows):
        h_lines.append(f"    S_{sid} = {i},")
    h_lines += [
        "    S_COUNT",
        "} StrId;",
        "",
        "typedef enum {",
        "    LANG_EN = 0,",
        "    LANG_ZH = 1",
        "} Language;",
        "",
        "const char *Str(StrId id);",
        "void Str_SetLanguage(int language);",
        "int Str_GetLanguage(void);",
        "",
        "#endif",
        "",
    ]

    c_lines = [
        "/* Generated by tools/gen_strings.py. Do not edit by hand. */",
        '#include "gen/strings_gen.h"',
        "",
        "static const char *const strings_en[S_COUNT] = {",
    ]
    for sid, en, _zh in rows:
        c_lines.append(f'    [S_{sid}] = "{c_escape(en)}",')
    c_lines += [
        "};",
        "",
        "static const char *const strings_zh[S_COUNT] = {",
    ]
    for sid, _en, zh in rows:
        c_lines.append(f'    [S_{sid}] = "{c_escape(zh)}",')
    c_lines += [
        "};",
        "",
        "static int language = LANG_EN;",
        "",
        "const char *Str(StrId id) {",
        "    if (id < 0 || id >= S_COUNT) return \"?\";",
        "    const char *text = language == LANG_ZH ? strings_zh[id]",
        "                                               : strings_en[id];",
        "    if (!text || text[0] == '\\0') text = strings_en[id];",
        "    return text ? text : \"?\";",
        "}",
        "",
        "void Str_SetLanguage(int new_language) {",
        "    if (new_language == LANG_ZH || new_language == LANG_EN) {",
        "        language = new_language;",
        "    }",
        "}",
        "",
        "int Str_GetLanguage(void) {",
        "    return language;",
        "}",
        "",
    ]

    h_path.write_text("\n".join(h_lines), encoding="utf-8")
    c_path.write_text("\n".join(c_lines), encoding="utf-8")
    print(
        f"generated {h_path.relative_to(ROOT)} and "
        f"{c_path.relative_to(ROOT)} ({len(rows)} strings)"
    )


if __name__ == "__main__":
    main()
