def pack_font() -> None:
    png_path = SRC_DIR / "font_en.png"
    meta_path = GEN_DIR / "font_en.json"
    if not png_path.exists() or not meta_path.exists():
        raise SystemExit("run tools/gen_font.py first")
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    image = Image.open(png_path).convert("RGBA")
    if image.size != (meta["atlas_w"], meta["atlas_h"]):
        raise SystemExit(f"font atlas size mismatch: {image.size}")
    write_font_header(image.tobytes(), meta)


