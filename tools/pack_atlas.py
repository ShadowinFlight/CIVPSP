#!/usr/bin/env python3
"""Pack generated PNG atlases into PSP GU texture data.

The English font is packed as GU_PSM_8888 (RGBA bytes).  The M1 terrain atlas
is packed as GU_PSM_5551 so resource icons can use 1-bit transparency while the
terrain tiles remain 16-bit (128KB at 256x256 with five civilization rows and
room for six unit/city icons per row).  The output is a C header with the raw
texture and metadata, so the PSP build does not decode PNGs at runtime.
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "assets" / "src"
GEN_DIR = ROOT / "assets" / "gen"
OUT_DIR = ROOT / "src" / "gen"


def write_font_header(data: bytes, meta: dict) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    h_path = OUT_DIR / "font_en.h"
    raw_path = GEN_DIR / "font_en.rgba.raw"
    raw_path.write_bytes(data)

    lines = [
        "/* Generated by tools/pack_atlas.py. Do not edit by hand. */",
        "#ifndef FONT_EN_H",
        "#define FONT_EN_H",
        "",
        f"#define FONT_ATLAS_W {meta['atlas_w']}",
        f"#define FONT_ATLAS_H {meta['atlas_h']}",
        f"#define FONT_CELL_W {meta['cell_w']}",
        f"#define FONT_CELL_H {meta['cell_h']}",
        f"#define FONT_COLS {meta['cols']}",
        f"#define FONT_ROWS {meta['rows']}",
        f"#define FONT_FIRST {meta['first']}",
        f"#define FONT_LAST {meta['last']}",
        "",
        "static const unsigned char font_en_rgba[] __attribute__((aligned(16))) = {",
    ]
    for start in range(0, len(data), 16):
        chunk = data[start : start + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines += [
        "};",
        "",
        "#endif",
        "",
    ]
    h_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"packed {h_path.relative_to(ROOT)} and {raw_path.relative_to(ROOT)} ({len(data)} bytes)")


def rgba_to_5551(image: Image.Image) -> bytes:
    """Return little-endian GU_PSM_5551 texels.

    The PSP 16-bit layout is R in bits 0-4, G in 5-9, B in 10-14, and alpha in
    bit 15 (oslib's oslRgbaGet5551 uses the same layout).
    """
    out = bytearray()
    pixels = image.tobytes()
    for i in range(0, len(pixels), 4):
        r, g, b, a = pixels[i : i + 4]
        if a < 128:
            value = 0
        else:
            value = (1 << 15) | ((b >> 3) << 10) | ((g >> 3) << 5) | (r >> 3)
        out.append(value & 0xFF)
        out.append((value >> 8) & 0xFF)
    return bytes(out)


def write_zh_font_header(data: bytes, meta: dict) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    h_path = OUT_DIR / "font_zh.h"
    raw_path = GEN_DIR / "font_zh.rgba.raw"
    raw_path.write_bytes(data)

    lines = [
        "/* Generated by tools/pack_atlas.py. Do not edit by hand. */",
        "#ifndef FONT_ZH_H",
        "#define FONT_ZH_H",
        "",
        f"#define FONT_ZH_ATLAS_W {meta['atlas_w']}",
        f"#define FONT_ZH_ATLAS_H {meta['atlas_h']}",
        f"#define FONT_ZH_CELL_W {meta['cell_w']}",
        f"#define FONT_ZH_CELL_H {meta['cell_h']}",
        f"#define FONT_ZH_COLS {meta['cols']}",
        f"#define FONT_ZH_ROWS {meta['rows']}",
        f"#define FONT_ZH_GLYPH_COUNT {meta['glyph_count']}",
        "",
        "typedef struct {",
        "    unsigned int codepoint;",
        "    unsigned short u, v, w, advance;",
        "} FontGlyph;",
        "",
        "static const FontGlyph font_zh_glyphs[FONT_ZH_GLYPH_COUNT]"
        " __attribute__((aligned(16))) = {",
    ]
    for glyph in meta["glyphs"]:
        lines.append(
            "    { %d, %d, %d, %d, %d },"
            % (
                glyph["cp"],
                glyph["u"],
                glyph["v"],
                glyph["w"],
                glyph["advance"],
            )
        )
    lines += [
        "};",
        "",
        "static const unsigned char font_zh_rgba[]"
        " __attribute__((aligned(16))) = {",
    ]
    for start in range(0, len(data), 16):
        chunk = data[start : start + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines += [
        "};",
        "",
        "#endif",
        "",
    ]
    h_path.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"packed {h_path.relative_to(ROOT)} and "
        f"{raw_path.relative_to(ROOT)} ({len(data)} bytes)"
    )


def write_terrain_header(data: bytes, meta: dict) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    h_path = OUT_DIR / "terrain_gen.h"
    raw_path = GEN_DIR / "terrain_atlas.5551.raw"
    raw_path.write_bytes(data)

    texels = [data[i] | (data[i + 1] << 8) for i in range(0, len(data), 2)]
    lines = [
        "/* Generated by tools/pack_atlas.py. Do not edit by hand. */",
        "#ifndef TERRAIN_GEN_H",
        "#define TERRAIN_GEN_H",
        "",
        f"#define TERRAIN_ATLAS_W {meta['atlas_w']}",
        f"#define TERRAIN_ATLAS_H {meta['atlas_h']}",
        f"#define TERRAIN_ATLAS_TILE_W {meta['tile_w']}",
        f"#define TERRAIN_ATLAS_TILE_H {meta['tile_h']}",
        f"#define TERRAIN_ATLAS_COLS {meta['terrain_cols']}",
        f"#define TERRAIN_ATLAS_ROWS {meta['terrain_rows']}",
        f"#define TERRAIN_ATLAS_RESOURCE_ROW {meta['resource_row']}",
        f"#define TERRAIN_ATLAS_UNIT_ROW {meta['unit_row']}",
        f"#define TERRAIN_ATLAS_UNIT_ROWS {meta['unit_rows']}",
        "",
        "static const unsigned short terrain_atlas_5551[] __attribute__((aligned(16))) = {",
    ]
    for start in range(0, len(texels), 12):
        chunk = texels[start : start + 12]
        lines.append("    " + ", ".join(f"0x{value:04X}" for value in chunk) + ",")
    lines += [
        "};",
        "",
        "#endif",
        "",
    ]
    h_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"packed {h_path.relative_to(ROOT)} and {raw_path.relative_to(ROOT)} ({len(data)} bytes)")


